#!/usr/bin/env python3
"""Generate cell-covering spheres from each original collision mesh AABB.

Every box cell lies inside its circumsphere, so triangle interiors, not just
vertices, are enclosed. Finger boxes include their full URDF prismatic travel.
"""
from pathlib import Path
import argparse
import copy
import numpy as np
import yaml
import xml.etree.ElementTree as ET
from generate_collision_boxes import bounds

ROOT = Path(__file__).resolve().parents[1]


def generate(root=ROOT):
    package = root / 'piper_dual_description'
    robot = ET.parse(package / 'urdf/dual_piper.urdf').getroot()
    covers = []
    for link in robot.findall('link'):
        name = link.get('name')
        if not name.startswith('left_'):
            continue
        collision = link.find('collision')
        mesh = collision.find('geometry/mesh')
        origin = collision.find('origin')
        if any(float(x) for key in ('xyz', 'rpy') for x in origin.get(key, '0 0 0').split()) or mesh.get('scale', '1 1 1') != '1 1 1':
            raise ValueError('Expected identity collision origins and mesh scales')
        lo, hi = np.array(bounds(package / mesh.get('filename').removeprefix('package://piper_dual_description/')))
        joint = next((j for j in robot.findall('joint') if j.find('child').get('link') == name), None)
        if joint is not None and joint.get('type') == 'prismatic':
            axis = np.fromstring(joint.find('axis').get('xyz'), sep=' ')
            limit = joint.find('limit')
            shift = np.array([axis * float(limit.get(k)) for k in ('lower', 'upper')])
            lo += shift.min(axis=0)
            hi += shift.max(axis=0)
        covers.append(dict(frame=name.removeprefix('left_'), bounds_min_m=lo.tolist(),
                           bounds_max_m=hi.tolist(), cell_size_m=.008 if name.endswith('gripper_base') else .04,
                           padding_m=.001))
    result = {side: {'mesh_covers': copy.deepcopy(covers)} for side in ('left', 'right')}
    path = root/'piper_collision_guard/config/protection_mesh_cover.yaml'
    path.write_text('# Generated by tools/generate_protection_spheres.py from source STL bounds.\n'
                    '# Full mesh AABB coverage + 1 mm radial padding; not measured stopping clearance.\n'
                    '# Finger covers include the complete URDF opening range; no payload model.\n'
                    + yaml.safe_dump(result, sort_keys=False))
    print(f'Generated {len(covers)} link covers per arm in {path}')


if __name__ == '__main__':
    generate()
